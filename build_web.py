"""Prepare the data the web page needs.

Run with:  .venv/bin/python build_web.py
It runs the engine for every zone, soil and planting month and writes:
  web/data.js          water needs, crop table and constants used by the page
  web/test_cases.json  sample scenarios with the engine's answers, used to
                       prove that the page calculates exactly like the engine
"""

import json
import random
from pathlib import Path

import nasa_power
import rotation
import water
from crops import CASH_CROPS, CROPS, LEGUMES

WEB = Path(__file__).parent / "web"
SOILS = ("clay", "loam", "sandy")
MONTHS = range(1, 13)


def rounded(value, digits=2):
    return round(float(value), digits)


def main():
    WEB.mkdir(exist_ok=True)
    zones, all_needs = [], {}

    for zone_name, zone in nasa_power.ZONES.items():
        daily, info = nasa_power.load(zone_name)
        et0 = water.reference_et(daily, zone["lat"], zone["elev"])
        usable = water.usable_rain(daily)

        # Typical month-by-month climate (2001-2025): rain and water lost by the field.
        monthly_rain = daily["rain"].resample("MS").sum()["2001":"2025"]
        monthly_et0 = et0.resample("MS").sum()["2001":"2025"]
        monthly_tmax = daily["tmax"].resample("MS").mean()["2001":"2025"]
        monthly_soil = 100 * daily["soil_root"].resample("MS").mean()["2001":"2025"]
        climate = {
            # root-zone soil wetness, % of saturation (NASA POWER GWETROOT)
            "soil": [rounded(v, 0) for v in monthly_soil.groupby(monthly_soil.index.month).mean()],
            "rain": [rounded(v, 0) for v in monthly_rain.groupby(monthly_rain.index.month).mean()],
            "et0": [rounded(v, 0) for v in monthly_et0.groupby(monthly_et0.index.month).mean()],
            "tmax": [rounded(v, 1) for v in monthly_tmax.groupby(monthly_tmax.index.month).mean()],
            "humidity": [rounded(v, 0) for v in daily["humidity"]["2001":"2025"].groupby(daily["2001":"2025"].index.month).mean()],
            "wind": [rounded(v, 1) for v in daily["wind"]["2001":"2025"].groupby(daily["2001":"2025"].index.month).mean()],
            "temp": [rounded(v, 1) for v in daily["temp"]["2001":"2025"].groupby(daily["2001":"2025"].index.month).mean()],
        }

        zones.append(
            {
                "name": zone_name,
                "lat": zone["lat"],
                "lon": zone["lon"],
                "elev": zone["elev"],
                "basin": zone["basin"],
                "cell_elev": rounded(info["cell_elevation"], 0),
                "temp_adjustment": rounded(info["temp_adjustment"], 1),
                "downloaded": info["downloaded"],
                "last_day": str(daily["temp"].last_valid_index().date()),
                "climate": climate,
            }
        )

        for soil in SOILS:
            for month in MONTHS:
                needs = water.crop_needs(daily, zone, soil, month, et0, usable)
                all_needs[f"{zone_name}|{soil}|{month}"] = {
                    crop: {
                        "typical_m3": rounded(n["typical_m3"]),
                        "dry_m3": rounded(n["dry_m3"]),
                        "tmax": rounded(n["tmax"]),
                        "rain_share": rounded(n["rain_share"], 3),
                        "days": n["days"],
                    }
                    for crop, n in needs.items()
                }
        print("computed", zone_name)

    data = {
        "zones": zones,
        "needs": all_needs,
        "crops": CROPS,
        "legumes": LEGUMES,
        "cash_crops": CASH_CROPS,
        "basins": rotation.BASINS,
        "constants": {
            "min_rotation_share": rotation.MIN_ROTATION_SHARE,
            "nitrogen_target_kg_ha": rotation.NITROGEN_TARGET_KG_HA,
            "urea_nitrogen": rotation.UREA_NITROGEN,
            "urea_sack_kg": rotation.UREA_SACK_KG,
            "priority_weight": rotation.PRIORITY_WEIGHT,
            "tareas_per_hectare": water.TAREAS_PER_HECTARE,
            "national_rice_tareas": rotation.NATIONAL_RICE_TAREAS,
        },
    }
    (WEB / "data.js").write_text(
        "// Generated by build_web.py from NASA POWER data. Do not edit by hand.\n"
        "window.GT_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )

    # Sample scenarios answered by the Python engine, from the same rounded needs.
    random.seed(2026)
    cases = []
    for _ in range(400):
        key = random.choice(list(all_needs))
        soil = key.split("|")[1]
        scenario = {
            "key": key,
            "soil": soil,
            "area": random.choice([5, 37.5, 100, 480]),
            "allocation": random.choice([0, 0.1, 0.3, 0.45, 0.6, 0.8, 1.0]),
            "priority": random.choice(["water", "soil", "income"]),
            "rice_allowed": random.random() > 0.3,
            "salty": random.random() > 0.7,
        }
        result = rotation.compare_needs(
            all_needs[key], soil, scenario["area"], scenario["allocation"],
            scenario["priority"], scenario["rice_allowed"], scenario["salty"],
        )
        cases.append({"scenario": scenario, "strategies": result["strategies"],
                      "budget_m3": result["budget_m3"]})
    basin_cases = [
        {"basin": basin, "rice": 900.0, "other": 200.0, "share": share,
         "expected": rotation.basin_savings(basin, 900.0, 200.0, share)}
        for basin in rotation.BASINS for share in (0.1, 0.25, 1.0)
    ]
    (WEB / "test_cases.json").write_text(
        json.dumps({"compare": cases, "basin": basin_cases}), encoding="utf-8"
    )
    print("wrote web/data.js and web/test_cases.json")


if __name__ == "__main__":
    main()
