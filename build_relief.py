"""Prepare the terrain relief the web page uses for its 3D zone view.

Run with:  .venv/bin/python build_relief.py
Downloads public elevation tiles (Terrain Tiles on AWS Open Data, "terrarium"
format, built by Mapzen mainly from NASA SRTM for these latitudes), decodes
them without extra libraries and writes:
  web/relief.js   a grid of elevations (meters) covering the Dominican Republic
It also prints the elevation at each rice zone.
"""

import base64
import math
import struct
import zlib
from pathlib import Path

import requests

import nasa_power

WEB = Path(__file__).parent / "web"
TILE_URL = "https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png"
ZOOM = 8
WEST, EAST, SOUTH, NORTH = -72.1, -68.2, 17.4, 20.05
STEP = 0.0125  # degrees between grid points (about 1.4 km)


def decode_png(data):
    """Return (width, height, rows of RGB tuples) from an 8-bit PNG."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    position, chunks, header = 8, [], None
    while position < len(data):
        length, kind = struct.unpack(">I4s", data[position:position + 8])
        body = data[position + 8:position + 8 + length]
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            chunks.append(body)
        position += 12 + length
    width, height, depth, color, _, _, interlace = header
    assert depth == 8 and color in (2, 6) and interlace == 0, header
    channels = 3 if color == 2 else 4
    raw = zlib.decompress(b"".join(chunks))
    stride = width * channels
    rows, previous = [], bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        kind = raw[start]
        line = bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - channels] if i >= channels else 0
            up = previous[i]
            corner = previous[i - channels] if i >= channels else 0
            if kind == 1:
                line[i] = (line[i] + left) & 255
            elif kind == 2:
                line[i] = (line[i] + up) & 255
            elif kind == 3:
                line[i] = (line[i] + (left + up) // 2) & 255
            elif kind == 4:
                p = left + up - corner
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - corner)
                best = left if pa <= pb and pa <= pc else (up if pb <= pc else corner)
                line[i] = (line[i] + best) & 255
        rows.append(line)
        previous = line
    return width, height, channels, rows


def tile_xy(lon, lat):
    """Fractional tile coordinates of a point (Web Mercator)."""
    n = 2 ** ZOOM
    x = (lon + 180) / 360 * n
    y = (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n
    return x, y


def main():
    tiles = {}

    def elevation(lon, lat):
        x, y = tile_xy(lon, lat)
        key = (int(x), int(y))
        if key not in tiles:
            response = requests.get(TILE_URL.format(z=ZOOM, x=key[0], y=key[1]), timeout=60)
            response.raise_for_status()
            tiles[key] = decode_png(response.content)
            print("tile", key)
        width, height, channels, rows = tiles[key]
        px = min(width - 1, int((x - key[0]) * width))
        py = min(height - 1, int((y - key[1]) * height))
        r, g, b = rows[py][px * channels:px * channels + 3]
        return r * 256 + g + b / 256 - 32768

    columns = int(round((EAST - WEST) / STEP)) + 1
    lines = int(round((NORTH - SOUTH) / STEP)) + 1
    values = []
    for j in range(lines):  # from north to south
        lat = NORTH - j * STEP
        for i in range(columns):
            values.append(max(0, min(65535, int(round(elevation(WEST + i * STEP, lat))))))
    packed = base64.b64encode(struct.pack("<%dH" % len(values), *values)).decode()
    (WEB / "relief.js").write_text(
        "// Generated by build_relief.py. Elevation in meters: Terrain Tiles (AWS Open Data),\n"
        "// derived mainly from NASA SRTM. Do not edit by hand.\n"
        "window.GT_RELIEF = {west:%s,north:%s,step:%s,columns:%d,rows:%d,data:\"%s\"};\n"
        % (WEST, NORTH, STEP, columns, lines, packed),
        encoding="utf-8",
    )
    print("wrote web/relief.js:", columns, "x", lines, "points,", len(packed) // 1024, "KB, max", max(values), "m")
    for name, zone in nasa_power.ZONES.items():
        print(f"{name:34s} listed {zone['elev']:5d} m   SRTM {elevation(zone['lon'], zone['lat']):6.0f} m")


if __name__ == "__main__":
    main()
