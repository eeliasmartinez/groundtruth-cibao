"""Prepare the real map shapes the web page draws.

Run with:  .venv/bin/python build_geo.py FOLDER
FOLDER must contain two downloaded files:
  countries.geojson  Natural Earth 1:10m countries (public domain)
                     https://github.com/nvkelso/natural-earth-vector
  rivers.json        OpenStreetMap rivers of the Dominican Republic, from the
                     Overpass API: way["waterway"="river"] inside the country,
                     "out geom". (c) OpenStreetMap contributors, ODbL.
It writes web/geo.js: coastline, rivers and dam markers, simplified so the
file stays small and the page keeps working without internet.
"""

import collections
import json
import math
import sys
from pathlib import Path

WEB = Path(__file__).parent / "web"
MAIN_RIVERS = ("Río Yaque del Norte", "Río Yuna", "Río Yaque del Sur")
ALWAYS = ("Río Mao", "Río Bao", "Río Jima", "Río Camú", "Río San Juan", "Río Masacre", "Río Jimenoa")
MIN_KM = 45  # other rivers are drawn only if they are at least this long

# Dams: approximate position, snapped to the nearest point of their river.
DAMS = [
    ("Tavera - Bao", "Río Yaque del Norte", -70.72, 19.28),
    ("Monción", "Río Mao", -71.17, 19.42),
    ("Hatillo", "Río Yuna", -70.25, 19.03),
    ("Rincón", "Río Jima", -70.40, 19.10),
    ("Sabana Yegua", "Río Yaque del Sur", -70.93, 18.73),
    ("Sabaneta", "Río San Juan", -71.30, 18.97),
]


def simplify(points, tolerance):
    """Douglas-Peucker: drop points that do not change the shape visibly."""
    if len(points) < 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        (x1, y1), (x2, y2) = points[first], points[last]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1e-12
        worst, index = 0.0, None
        for i in range(first + 1, last):
            x, y = points[i]
            distance = abs(dy * (x - x1) - dx * (y - y1)) / norm
            if distance > worst:
                worst, index = distance, i
        if index is not None and worst > tolerance:
            keep[index] = True
            stack.append((first, index))
            stack.append((index, last))
    return [p for p, k in zip(points, keep) if k]


def simplify_ring(ring, tolerance):
    """A coastline starts and ends at the same point, so it is simplified in two halves."""
    middle = len(ring) // 2
    return simplify(ring[: middle + 1], tolerance) + simplify(ring[middle:], tolerance)[1:]


def rounded(points):
    return [[round(x, 3), round(y, 3)] for x, y in points]


def km(points):
    return sum(math.hypot((a[0] - b[0]) * 104, (a[1] - b[1]) * 111) for a, b in zip(points, points[1:]))


def main(folder):
    folder = Path(folder)
    countries = json.loads((folder / "countries.geojson").read_text(encoding="utf-8"))
    shapes = {}
    for feature in countries["features"]:
        code = feature["properties"].get("ADM0_A3")
        if code in ("DOM", "HTI"):
            geometry = feature["geometry"]
            polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
            shapes[code] = [rounded(simplify_ring(polygon[0], 0.002)) for polygon in polygons]

    osm = json.loads((folder / "rivers.json").read_text(encoding="utf-8"))
    by_name = collections.defaultdict(list)
    for way in osm["elements"]:
        name = way.get("tags", {}).get("name")
        if not name:
            continue
        name = "Río Yaque del Norte" if name.lower() == "rio yaque del norte" else name
        by_name[name].append([(p["lon"], p["lat"]) for p in way["geometry"]])

    rivers = []
    for name, lines in by_name.items():
        length = sum(km(line) for line in lines)
        if name in MAIN_RIVERS or name in ALWAYS or length >= MIN_KM:
            rivers.append({
                "name": name,
                "main": name in MAIN_RIVERS,
                "lines": [rounded(simplify(line, 0.0015)) for line in lines if len(line) > 1],
            })

    dams = []
    for name, river, lon, lat in DAMS:
        candidates = [p for line in by_name.get(river, []) for p in line]
        if candidates:
            lon, lat = min(candidates, key=lambda p: (p[0] - lon) ** 2 + (p[1] - lat) ** 2)
        dams.append({"name": name, "lon": round(lon, 3), "lat": round(lat, 3)})

    geo = {"land": shapes["DOM"], "haiti": shapes["HTI"], "rivers": rivers, "dams": dams}
    text = json.dumps(geo, ensure_ascii=False, separators=(",", ":"))
    (WEB / "geo.js").write_text(
        "// Generated by build_geo.py. Coastline: Natural Earth (public domain).\n"
        "// Rivers: (c) OpenStreetMap contributors, ODbL. Do not edit by hand.\n"
        "window.GT_GEO = " + text + ";\n",
        encoding="utf-8",
    )
    points = sum(len(line) for river in rivers for line in river["lines"])
    print(f"wrote web/geo.js: {len(text) // 1024} KB, {len(rivers)} rivers, {points} river points, "
          f"{sum(len(r) for r in shapes['DOM'])} coast points")
    print("dams:", dams)


if __name__ == "__main__":
    main(sys.argv[1])
